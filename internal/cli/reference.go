package cli

import (
	"fmt"
	"html/template"
	"io"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// refFlag and refCommand describe the CLI for the generated reference.
type refFlag struct {
	Name, Short, Type, Default, Usage string
}

type refCommand struct {
	ID, Path, Use, Short, Long, Example string
	Flags                               []refFlag
}

func collect(root *cobra.Command) []refCommand {
	var out []refCommand
	var walk func(*cobra.Command)
	walk = func(c *cobra.Command) {
		if c.Hidden || c.Name() == "help" {
			return
		}
		if c.Runnable() {
			rc := refCommand{
				ID:      strings.ReplaceAll(c.CommandPath(), " ", "-"),
				Path:    c.CommandPath(),
				Use:     c.UseLine(),
				Short:   c.Short,
				Long:    strings.TrimSpace(c.Long),
				Example: strings.TrimRight(c.Example, "\n"),
			}
			c.NonInheritedFlags().VisitAll(func(f *pflag.Flag) {
				if f.Hidden || f.Name == "help" {
					return
				}
				typ := f.Value.Type()
				if typ == "bool" {
					typ = ""
				}
				def := f.DefValue
				if def == "[]" || def == "false" || (typ == "string" && def == "") {
					def = ""
				}
				rc.Flags = append(rc.Flags, refFlag{Name: f.Name, Short: f.Shorthand, Type: typ, Default: def, Usage: f.Usage})
			})
			sort.Slice(rc.Flags, func(i, j int) bool { return rc.Flags[i].Name < rc.Flags[j].Name })
			out = append(out, rc)
		}
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	return out
}

var referenceTemplate = template.Must(template.New("ref").Parse(`{{range .}}
<section class="cmd" id="{{.ID}}">
  <h3><a href="#{{.ID}}">{{.Path}}</a></h3>
  <p class="lead">{{.Short}}</p>
  <pre class="usage"><code>{{.Use}}</code></pre>
  {{if .Long}}<p>{{.Long}}</p>{{end}}
  {{if .Flags}}<div class="table-wrap"><table class="flags">
    <thead><tr><th>Flag</th><th>Default</th><th>Description</th></tr></thead>
    <tbody>{{range .Flags}}
      <tr><td><code>{{if .Short}}-{{.Short}}, {{end}}--{{.Name}}{{if .Type}} <i>{{.Type}}</i>{{end}}</code></td><td>{{if .Default}}<code>{{.Default}}</code>{{end}}</td><td>{{.Usage}}</td></tr>{{end}}
    </tbody></table></div>{{end}}
  {{if .Example}}<p class="label">Examples</p><pre class="example"><code>{{.Example}}</code></pre>{{end}}
</section>{{end}}
`))

// newReferenceCmd prints the command reference used by acurl.dev. It is
// hidden: the site build runs it so the docs always match the CLI.
func newReferenceCmd(a *app, root *cobra.Command) *cobra.Command {
	return &cobra.Command{
		Use:    "reference",
		Short:  "Print the command reference as HTML for acurl.dev",
		Args:   cobra.NoArgs,
		Hidden: true,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return writeReference(a.stdout, root)
		},
	}
}

func writeReference(w io.Writer, root *cobra.Command) error {
	cmds := collect(root)
	global := refCommand{ID: "global-flags", Path: "Global flags", Use: "acurl [command] [flags]", Short: "These flags work with every command."}
	root.PersistentFlags().VisitAll(func(f *pflag.Flag) {
		typ, def := f.Value.Type(), f.DefValue
		if typ == "bool" {
			typ, def = "", ""
		}
		global.Flags = append(global.Flags, refFlag{Name: f.Name, Short: f.Shorthand, Type: typ, Default: def, Usage: f.Usage})
	})
	cmds = append(cmds, global)
	if _, err := fmt.Fprintln(w, "<!-- generated by acurl reference; do not edit -->"); err != nil {
		return err
	}
	return referenceTemplate.Execute(w, cmds)
}
